// scripts/d133StudioTokens.mjs — ⭐ D133 · writes client/src/themes/studio-light.js and studio-dark.js: the admin sketch's
// look (docs/sketches/draft admin — testers.html) as a registry theme. Every key is written out (a theme file imports no
// other theme, D91): Paper Light's / Charcoal Dark's values, with the sketch's over the keys it names (OVERRIDES).
// Change OVERRIDES and run `node scripts/d133StudioTokens.mjs`; test/d91ThemeModule.test.js holds every pair at AA.
import fs from "node:fs";
import paperLight from "../client/src/themes/paper-light.js";
import charcoalDark from "../client/src/themes/charcoal-dark.js";

const OVERRIDES = {
  "studio-light": { base: paperLight, label: "Studio Light", scheme: "light", tokens: {
    CANVAS: ["#F2F0EB", "the sketch's --bg"], CANVAS_SHADE: ["#E9E6DF", "a step below the ground"],
    SURFACE: ["rgba(255,255,255,0.94)", "flat white cards"], SURFACE_2: ["rgba(250,249,246,0.96)", "flat"],
    SURFACE_SOLID: ["#FFFFFF", "the sketch's --surface"], INK: ["#1B1A18", "--ink"], INK_MUTED: ["#5F5B54", "--muted"],
    BORDER: ["#D8D4CC", "--line"], INFO: ["#1A5AAE", "--bar #2F7FE0, deepened to hold 4.5:1 as text on its quiet tint"],
    SUCCESS: ["#166B3A", "--ok #1E7A43, deepened to hold 4.5:1 on the shade and its quiet tint"],
    WARNING: ["#8A5A00", "--warn #9A6400, deepened for 4.5:1 on the ground"] },
    substrate: { grain: 0 } },
  "studio-dark": { base: charcoalDark, label: "Studio Dark", scheme: "dark", tokens: {
    CANVAS: ["#121213", "the sketch's --bg"], CANVAS_SHADE: ["#18181A", "a step toward the sheen, as Charcoal's"],
    SURFACE: ["rgba(28,29,31,0.94)", "flat charcoal cards"], SURFACE_2: ["rgba(38,40,43,0.94)", "the sketch's --well"],
    SURFACE_SOLID: ["#1C1D1F", "the sketch's --surface"], INK: ["#ECEAE6", "--ink"], INK_MUTED: ["#A8A39B", "--muted"],
    BORDER: ["#34363A", "--line"], INFO: ["#6FA8E8", "--bar"], SUCCESS: ["#62C98A", "--ok"], WARNING: ["#E8B14F", "--warn"] },
    substrate: { grain: 0, sheen: 0 } },
};

for (const [id, o] of Object.entries(OVERRIDES)) {
  const keys = Object.keys(o.base.tokens);
  const w = Math.max(...keys.map(k => k.length)) + 2;
  const lines = keys.map(k => {
    const [v, why] = o.tokens[k] || [o.base.tokens[k], null];
    return `  ${(k + ":").padEnd(w)}${JSON.stringify(v)},${why ? `   // ${why}` : ""}`;
  });
  const sub = { ...o.base.substrate, ...o.substrate };
  const file = `// ── ${o.label.toUpperCase()} — the admin sketch's look as a theme (D133) ──────────────────────────────────────────
//
// Owner 11-01: "the theme you used to visualise this is kinda nice. why dont we have it as a wrapper theme and be able
// to apply it to the admin or the site when we want". The look of docs/sketches/draft admin — testers.html: a quiet
// ground, flat cards with a 1 px line, a muted grey for labels, blue for ordinary bars and information, the brand orange
// kept for the one thing that matters; no grain. ⛔ GENERATED by scripts/d133StudioTokens.mjs — do not hand-edit:
// change its OVERRIDES and run it. Keys with a note are the sketch's; every other key is ${o.base.label}'s, unchanged.
// Radii and type are not theme keys (THEME_MODULE.md §5, "effects stay put").
const tokens = Object.freeze({
${lines.join("\n")}
});

export default Object.freeze({
  id: ${JSON.stringify(id)},
  label: ${JSON.stringify(o.label)},
  scheme: ${JSON.stringify(o.scheme)},
  contrast: "aa",
  tokens,
  // ${o.base.label}'s substrate, flat: the sketch has no grain.
  substrate: Object.freeze(${JSON.stringify(sub).replace(/"(\w+)":/g, "$1: ").replace(/,/g, ", ").replace(/^\{/, "{ ").replace(/\}$/, " }")}),
});
`;
  fs.writeFileSync(`client/src/themes/${id}.js`, file);
  console.log(`wrote client/src/themes/${id}.js (${keys.length} keys, ${Object.keys(o.tokens).length} from the sketch)`);
}
