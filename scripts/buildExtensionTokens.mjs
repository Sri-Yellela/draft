#!/usr/bin/env node
/**
 * D23 — the extension's visual language is the SITE'S, from the site's one definition.
 *
 * The extension carried its own palette (teal #01696F, a grey-cream #F7F6F2, the review overlay's
 * slate #0f172a) — a hand copy of a design that had since been replaced, which is exactly how a
 * palette rots. It now consumes the SAME source the site does:
 *
 *   client/src/styles/colorTokens.js  ->  extension/tokens.css   the --c-* custom properties, light
 *                                                                 in :root and dark under
 *                                                                 prefers-color-scheme (the popup and
 *                                                                 the options page link it)
 *                                     ->  extension/tokens.js    the same values as an ES module, for
 *                                                                 what is injected into a page (the
 *                                                                 review overlay, the capture toast)
 *                                                                 and the toolbar badge
 *
 * and copies, byte for byte, the assets the site's look depends on:
 *
 *   client/src/assets/brand/wordmark-{slash,letters}.png  ->  extension/brand/   the /draft mark as the
 *       two D19 masks, filled from var(--c-logo-slash) / var(--c-logo-word) like StampLogo does
 *   @fontsource/poppins 800 italic (latin, latin-ext)      ->  extension/fonts/   "the logo face"
 *   @fontsource/dm-sans 400/500/700 (latin)                ->  extension/fonts/   the body face
 *
 * Self-hosted: the extension makes no font request to anyone (the site stopped asking Google for
 * fonts on 2026-09-15 for the same reason). The font files carry their OFL notice in their own name
 * table, which the OFL accepts.
 *
 * Generated files are committed (a store package must be buildable from the commit), and
 * test/d23ExtensionLook.test.js fails if any of them differs from what this script would write now —
 * so a token change on the site that is not regenerated here fails the suite, and a hand edit to
 * extension/tokens.css fails it too. scripts/buildExtension.mjs refuses to package a stale set.
 *
 *   node scripts/buildExtensionTokens.mjs           write
 *   node scripts/buildExtensionTokens.mjs --check   exit 1 if anything is stale; write nothing
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const EXT = path.join(ROOT, "extension");
const FONTSOURCE = path.join(ROOT, "client", "node_modules", "@fontsource");

/** extension-relative path -> absolute source path, copied byte for byte. */
export const COPIED_ASSETS = {
  "brand/wordmark-slash.png":   path.join(ROOT, "client/src/assets/brand/wordmark-slash.png"),
  "brand/wordmark-letters.png": path.join(ROOT, "client/src/assets/brand/wordmark-letters.png"),
  "fonts/poppins-latin-800-italic.woff2":     path.join(FONTSOURCE, "poppins/files/poppins-latin-800-italic.woff2"),
  "fonts/poppins-latin-ext-800-italic.woff2": path.join(FONTSOURCE, "poppins/files/poppins-latin-ext-800-italic.woff2"),
  "fonts/dm-sans-latin-400-normal.woff2":     path.join(FONTSOURCE, "dm-sans/files/dm-sans-latin-400-normal.woff2"),
  "fonts/dm-sans-latin-500-normal.woff2":     path.join(FONTSOURCE, "dm-sans/files/dm-sans-latin-500-normal.woff2"),
  "fonts/dm-sans-latin-700-normal.woff2":     path.join(FONTSOURCE, "dm-sans/files/dm-sans-latin-700-normal.woff2"),
  // ⭐ T9: the ATS report's score is set in the display serif (--font-display), as on the site.
  "fonts/instrument-serif-latin-400-normal.woff2":     path.join(FONTSOURCE, "instrument-serif/files/instrument-serif-latin-400-normal.woff2"),
  "fonts/instrument-serif-latin-ext-400-normal.woff2": path.join(FONTSOURCE, "instrument-serif/files/instrument-serif-latin-ext-400-normal.woff2"),
};

// The unicode ranges are @fontsource's own (poppins/800-italic.css, dm-sans/400.css), so the browser
// picks the same file for the same character as it does on the site.
const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
const LATIN_EXT = "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF";

const HEADER =
  "GENERATED by scripts/buildExtensionTokens.mjs from client/src/styles/colorTokens.js — do not edit.\n" +
  "   Change the token on the site and run: node scripts/buildExtensionTokens.mjs\n" +
  "   test/d23ExtensionLook.test.js fails if this file and the site's tokens disagree.";

function fontFace(family, style, weight, file, range) {
  return `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n` +
         `  font-display: swap;\n  src: url(${file}) format('woff2');\n  unicode-range: ${range};\n}\n`;
}

/** The two generated text files, as strings (LF). */
export async function renderExtensionTokens() {
  const mod = await import(pathToFileURL(path.join(ROOT, "client/src/styles/colorTokens.js")).href);
  const { C_LIGHT, C_DARK, cssVarName } = mod;
  // ⛔ D32: the ink pair's tokens (PAIR_*) do NOT travel. The pair — the posting and the score side by
  // side — is the site's ONLY dark surface, and a rule rather than a per-screen choice: the extension
  // draws no pair, so it carries none of its tokens (test/inkPairD32.test.js).
  // D35: nor do the Full House header's (FH_*) — the extension draws no board header.
  // D48: nor do the posting panel's (PP_*) — the extension draws no posting panel. ⭐ D63: except the ATS
  // NUMBER, which the popup's job card now draws in the same number box (D50), so it is one colour everywhere.
  // D91: nor the document surface (DOC_*) — the extension shows no document.
  // A228: nor the charts' neutral (CHART_*) — the extension draws no chart.
  const names = Object.keys(C_LIGHT).filter((n) => !n.startsWith("PAIR_") && !n.startsWith("FH_") && (!n.startsWith("PP_") || n === "PP_ATS_NUMBER") && !n.startsWith("DOC_") && !n.startsWith("CHART_"));
  const missing = names.filter((n) => !(n in C_DARK));
  if (missing.length) throw new Error(`colorTokens.js: C_DARK lacks ${missing.join(", ")}`);

  const block = (pal) => names.map((n) => `  ${cssVarName(n)}: ${pal[n]};`).join("\n");
  const css =
    `/* ${HEADER} */\n\n` +
    `/* The light palette is the default; the dark one follows the OS, as the site's "system"\n` +
    `   preference does. (The site's per-account choice lives in the site's own storage, which the\n` +
    `   extension does not read: no new storage key, D23.) */\n` +
    `:root {\n  color-scheme: light;\n${block(C_LIGHT)}\n}\n` +
    `@media (prefers-color-scheme: dark) {\n  :root {\n  color-scheme: dark;\n${block(C_DARK)}\n  }\n}\n\n` +
    `/* The logo face — the heavy italic geometric sans of the mark, the /d and the job cards'\n` +
    `   company names (D1) — and the body face. Self-hosted: no font request leaves the extension. */\n` +
    fontFace("Poppins", "italic", 800, "fonts/poppins-latin-ext-800-italic.woff2", LATIN_EXT) +
    fontFace("Poppins", "italic", 800, "fonts/poppins-latin-800-italic.woff2", LATIN) +
    fontFace("DM Sans", "normal", 400, "fonts/dm-sans-latin-400-normal.woff2", LATIN) +
    fontFace("DM Sans", "normal", 500, "fonts/dm-sans-latin-500-normal.woff2", LATIN) +
    fontFace("DM Sans", "normal", 700, "fonts/dm-sans-latin-700-normal.woff2", LATIN) +
    // ⭐ T9: the display serif — the ATS report's number (shared/atsReportStyles.js .ats-sum__score).
    fontFace("Instrument Serif", "normal", 400, "fonts/instrument-serif-latin-ext-400-normal.woff2", LATIN_EXT) +
    fontFace("Instrument Serif", "normal", 400, "fonts/instrument-serif-latin-400-normal.woff2", LATIN);

  const obj = (pal) => "Object.freeze({\n" + names.map((n) => `  ${n}: ${JSON.stringify(pal[n])},`).join("\n") + "\n})";
  // ⭐ T17: the dock (extension/dock.js) and every view on it are drawn in ALL FOUR of the registry's themes — the
  // account's appearance (GET /api/settings/appearance) picks the pair, gated-handoff.js overlayTheme() resolves it. The
  // two Paper / Charcoal palettes ARE C_LIGHT / C_DARK (colorTokens.js re-exports them), so only the Contrast pair is new.
  const { THEME_LIST } = await import(pathToFileURL(path.join(ROOT, "client/src/themes/index.js")).href);
  const byId = Object.fromEntries(THEME_LIST.map((t) => [t.id, t]));
  for (const t of THEME_LIST) {
    const lacking = names.filter((n) => !(n in t.tokens));
    if (lacking.length) throw new Error(`themes/${t.id}.js lacks ${lacking.join(", ")}`);
  }
  const constOf = { "paper-light": "C_LIGHT", "charcoal-dark": "C_DARK", "contrast-light": "C_CONTRAST_LIGHT", "contrast-dark": "C_CONTRAST_DARK",
    "studio-light": "C_STUDIO_LIGHT", "studio-dark": "C_STUDIO_DARK", "dusk-light": "C_DUSK_LIGHT", "dusk-dark": "C_DUSK_DARK",
    "plain-light": "C_PLAIN_LIGHT", "plain-dark": "C_PLAIN_DARK" };   // D181
  const unknown = THEME_LIST.map((t) => t.id).filter((id) => !constOf[id]);
  if (unknown.length) throw new Error(`a theme the extension does not carry yet: ${unknown.join(", ")} — add it to constOf`);
  const js =
    `/* ${HEADER} */\n\n` +
    `// For what cannot link tokens.css: code injected into a page by executeScript (the review overlay,\n` +
    `// the capture toast) receives these values as an argument, and the service worker paints the\n` +
    `// toolbar badge from them.\n` +
    `export const C_LIGHT = ${obj(C_LIGHT)};\n\n` +
    `export const C_DARK = ${obj(C_DARK)};\n\n` +
    `// ⭐ T17: the registry's Contrast pair (client/src/themes/contrast-*.js), for the dock and its views.\n` +
    `export const C_CONTRAST_LIGHT = ${obj(byId["contrast-light"].tokens)};\n\n` +
    `export const C_CONTRAST_DARK = ${obj(byId["contrast-dark"].tokens)};\n\n` +
    `// ⭐ D133: the registry's Studio pair (client/src/themes/studio-*.js), so an account on Studio sees it in the dock too.\n` +
    `export const C_STUDIO_LIGHT = ${obj(byId["studio-light"].tokens)};\n\n` +
    `export const C_STUDIO_DARK = ${obj(byId["studio-dark"].tokens)};\n\n` +
    `// ⭐ D144: the registry's Dusk pair (client/src/themes/dusk-*.js), so an account on Dusk sees it in the dock too.\n` +
    `export const C_DUSK_LIGHT = ${obj(byId["dusk-light"].tokens)};\n\n` +
    `export const C_DUSK_DARK = ${obj(byId["dusk-dark"].tokens)};\n\n` +
    // D181 (45l): the Plain pair — constOf named them but nothing emitted them (C_PLAIN_LIGHT is not defined).
    `export const C_PLAIN_LIGHT = ${obj(byId["plain-light"].tokens)};\n\n` +
    `export const C_PLAIN_DARK = ${obj(byId["plain-dark"].tokens)};\n\n` +
    `/** Every theme of the registry, by id: its scheme and its palette. */\n` +
    `export const EXT_THEMES = Object.freeze({\n` +
    THEME_LIST.map((t) => `  ${JSON.stringify(t.id)}: Object.freeze({ scheme: ${JSON.stringify(t.scheme)}, tokens: ${constOf[t.id]} }),`).join("\n") +
    `\n});\n\n` +
    `export const cssVarName = (name) => \`--c-\${name.toLowerCase().replace(/_/g, "-")}\`;\n`;
  return { "tokens.css": css, "tokens.js": js };
}

/** Every path that is stale or missing, extension-relative. Empty means up to date. */
export async function staleExtensionTokens() {
  const stale = [];
  const text = await renderExtensionTokens();
  for (const [rel, want] of Object.entries(text)) {
    const file = path.join(EXT, rel);
    const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
    if (have !== want) stale.push(rel);
  }
  for (const [rel, src] of Object.entries(COPIED_ASSETS)) {
    const file = path.join(EXT, rel);
    if (!fs.existsSync(src)) throw new Error(`source asset missing: ${path.relative(ROOT, src)} — run npm ci in client/`);
    if (!fs.existsSync(file) || !fs.readFileSync(file).equals(fs.readFileSync(src))) stale.push(rel);
  }
  // ⭐ T9: the ATS report the popup and the on-page panel draw is the web app's component, bundled
  // (scripts/buildAtsReport.mjs) — a package built from a stale bundle would ship last week's report.
  const { staleAtsReport } = await import("./buildAtsReport.mjs");
  for (const rel of await staleAtsReport()) stale.push(rel.replace(/^extension\//, ""));
  return stale;
}

async function main() {
  if (process.argv.includes("--check")) {
    const stale = await staleExtensionTokens();
    if (stale.length) { console.error(`[extensionTokens] stale: ${stale.join(", ")}`); process.exit(1); }
    console.log("[extensionTokens] up to date");
    return;
  }
  const text = await renderExtensionTokens();
  for (const [rel, body] of Object.entries(text)) fs.writeFileSync(path.join(EXT, rel), body);
  for (const [rel, src] of Object.entries(COPIED_ASSETS)) {
    fs.mkdirSync(path.dirname(path.join(EXT, rel)), { recursive: true });
    fs.copyFileSync(src, path.join(EXT, rel));
  }
  console.log(`[extensionTokens] wrote ${Object.keys(text).length} files, copied ${Object.keys(COPIED_ASSETS).length} assets`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) await main();
