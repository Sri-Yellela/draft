/**
 * ⭐ T18 · THE RÉSUMÉ FIELD IN A MANUAL FILL — the real extension on the Workday-shaped fixture (owner, field report 4).
 * ================================================================================================================
 *   npm run walk:extension -- resumeField [--theme dark]
 *
 * Proves, in a real Chrome, on the SHIPPED router, with the extension's résumé routes mounted (routes/extensionResume.js,
 * the generation and the PDF renderer STUBBED — test-support/extensionResumeStub.mjs; nothing leaves the machine):
 *   1. My Experience, Prepare: the review panel's "Resume/CV" row is a résumé upload under Needs you, offering
 *      Attach my résumé · Generate and attach · Skip (no tailored résumé exists yet) — and the fill ATTACHED NOTHING
 *   2. Attach my résumé (the user's click): the BASE résumé, rendered by draft's own server (GET
 *      /api/extension/base-resume/pdf/file — no model, no slot), lands in Workday's hidden drop-zone input; the page
 *      shows the file's name; the row moves to Filled with the name — nothing generated
 *   3. a fresh My Experience, Generate and attach (the user's click): ONE generation starts (RESUME_GENERATE with the
 *      click) and the dock's Résumé tab opens on it
 *   4. Skip on the REQUIRED upload keeps it under Needs you, saying so
 * Synthetic person (Ada Example) throughout.
 */
import { waitUntil, sleep, defaultSeed, BUSY_MS } from '../extensionBrowser.mjs';
import { mountExtensionResume, seedBaseResume } from '../extensionResumeStub.mjs';
import { prepareAndRead, fresh } from './panelLifecycle.mjs';

let CTL = null;
export const options = {
  api: {
    seed: (db) => { defaultSeed(db); seedBaseResume(db); },
    mount: async (app, db) => { CTL = mountExtensionResume(app, db); },
  },
};

export const description = 'T18: the résumé row — Attach my résumé (base, verified on the page), Generate and attach (one start, the click), Skip; nothing attached without the click';

const OVERLAY = 'rm-gate-review-overlay';
const resumeRow = (h) => h.readShadow(OVERLAY, (root) => {
  const rows = [...root.querySelectorAll('.rm-row')];
  const r = rows.find(x => x.querySelector('[data-role="label"]')?.textContent === 'Resume/CV');
  if (!r) return null;
  return { idx: r.dataset.idx, group: r.dataset.group, value: r.querySelector('[data-role="value"]')?.textContent || null,
    note: [...r.querySelectorAll('.rm-note')].map(n => n.textContent).join(' | '),
    choices: [...r.querySelectorAll('[data-role="file-choices"] button')].map(b => b.textContent) };
});
const status = (h) => h.page.$eval('#ws-resume-status', el => el.textContent).catch(() => '');
const files = (h) => h.page.evaluate(() => document.getElementById('ws-resume')?.files?.length ?? -1);

export default async function run(h, { check, observe, section }) {
  section('1 · My Experience, Prepare — the résumé row offers its choices; the fill attached nothing');
  await h.openStage('applyManually');
  const cap = await h.capture();
  check('captured — the tab is bound to the job', cap?.success === true, cap?.message);
  await h.goStep('myExperience');
  const filled = await prepareAndRead(h);
  observe('prepare', { ok: filled?.reply?.ok, resume: filled?.reply?.resume || null });
  const r1 = await waitUntil(() => resumeRow(h), BUSY_MS, 150);
  observe('the résumé row', r1);
  check('"Resume/CV" is a Needs-you row', r1?.group === 'need', JSON.stringify(r1));
  check('…offering Attach my résumé · Generate and attach · Skip (no tailored résumé yet)', r1?.choices.join(' · ') === 'Attach my résumé · Generate and attach · Skip', r1?.choices.join(' · '));
  check('…named as the résumé upload', /Your résumé goes here/.test(r1?.note || ''), r1?.note);
  check('⛔ the fill attached nothing — a file waits for the click', (await files(h)) === 0 && !/Successfully Uploaded/.test(await status(h)), await status(h));
  check('nothing was generated by the fill or the panel', CTL.generations().length === 0);

  section('2 · Attach my résumé — the base résumé, on the drop zone, verified');
  await h.page.click(`#${OVERLAY} >>> .rm-row[data-idx="${r1?.idx}"] [data-role="attach"][data-which="base"]`);
  const shown = await waitUntil(async () => { const s = await status(h); return /Successfully Uploaded/.test(s) ? s : null; }, BUSY_MS, 150);
  observe('the drop zone', shown);
  check('the page shows the file\'s name', /Ada_Example_Resume\.pdf · Successfully Uploaded!/.test(shown || ''), shown);
  check('…the PDF came from draft\'s base-résumé route', h.api.requests.some(q => q.method === 'GET' && q.path === '/api/extension/base-resume/pdf/file'));
  check('…rendered from the BASE résumé by draft\'s own renderer — no generation, no slot', CTL.rendered.length === 1 && /distributed systems/.test(CTL.rendered[0]) && CTL.generations().length === 0 && CTL.slots() === 0,
    `${CTL.rendered.length} renders, ${CTL.generations().length} generations`);
  const r2 = await waitUntil(async () => { const r = await resumeRow(h); return r?.group === 'ok' ? r : null; }, BUSY_MS, 150);
  check('the row moves to Filled with the file\'s name', r2?.value === 'Ada_Example_Resume.pdf', JSON.stringify(r2));

  section('3 · Generate and attach — one start, the user\'s click; the Résumé tab opens on it');
  await h.page.click('#rm-draft-dock >>> [data-role="close"]').catch(() => {});
  await fresh(h);
  await h.goStep('myExperience');
  await prepareAndRead(h);
  const r3 = await waitUntil(() => resumeRow(h), BUSY_MS, 150);
  check('a fresh step offers the choices again', (r3?.choices || []).includes('Generate and attach'), JSON.stringify(r3?.choices));
  await h.page.click(`#${OVERLAY} >>> .rm-row[data-idx="${r3?.idx}"] [data-role="generate"]`);
  const started = await waitUntil(() => (CTL.generations().length ? CTL.generations() : null), BUSY_MS, 150);
  check('ONE generation started', started?.length === 1, JSON.stringify(started));
  check('…by the click\'s own request', h.api.requests.filter(q => q.method === 'POST' && q.path === '/api/extension/resume').length === 1);
  const tab = await waitUntil(() => h.readShadow('rm-resume-panel', (root, host) => host.dataset.state || null), BUSY_MS, 150);
  check('…and the dock\'s Résumé tab shows it', ['queued', 'generating', 'ready'].includes(tab), tab);

  section('4 · Skip on the REQUIRED upload keeps it under Needs you');
  await h.page.click('#rm-draft-dock >>> [data-role="close"]').catch(() => {});
  await fresh(h);
  await h.goStep('myExperience');
  await prepareAndRead(h);
  const r4 = await waitUntil(() => resumeRow(h), BUSY_MS, 150);
  await h.page.click(`#${OVERLAY} >>> .rm-row[data-idx="${r4?.idx}"] [data-role="skip"]`);
  await sleep(300);
  const r5 = await resumeRow(h);
  check('still Needs you, saying the upload is required', r5?.group === 'need' && /this upload is required; attach a file on the page/.test(r5?.note || ''), JSON.stringify(r5));
  check('…and nothing was attached', (await files(h)) === 0);
  check('the fixture recorded no submission (draft never submits)', (await h.submissions()).length === 0);
  await h.screenshot(`t18-resume-field-${h.theme()}`);
}
