const read = (f) => fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n");
const REG = await import("../client/src/themes/index.js");
const { THEME_LIST, THEMES, DUSK_IDS, resolve, pairPreference, THEME_PREFERENCES } = REG;
