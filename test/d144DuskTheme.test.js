const hex = (v) => { const m = /^#([0-9a-f]{6})$/i.exec(v); return m ? [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16)) : null; };
const ch = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = ([r, g, b]) => 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b);
const ratio = (a, b) => { const [x, y] = [lum(hex(a)), lum(hex(b))].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

test("d144DuskTokensOnly: Dusk Light / Dark are registry data — every key, no import, generated, flat", () => {
  assert.deepEqual(DUSK_IDS, ["dusk-light", "dusk-dark"]);
  const keys = Object.keys(THEMES["paper-light"].tokens).sort();
  for (const id of DUSK_IDS) {
    const t = THEMES[id], src = read(`client/src/themes/${id}.js`);
    assert.deepEqual(Object.keys(t).sort(), ["contrast", "id", "label", "scheme", "substrate", "tokens"]);
    assert.deepEqual(Object.keys(t.tokens).sort(), keys, `${id} supplies every key`);
    assert.doesNotMatch(src, /^import /m, `${id} imports nothing`);
    assert.match(src, /GENERATED by scripts\/d144DuskTokens\.mjs/);
    assert.equal(t.substrate.grain, 0);
  }
  const d = THEMES["dusk-dark"].tokens, l = THEMES["dusk-light"].tokens;
  assert.equal(d.CANVAS, "#1B1B1B"); assert.equal(d.SURFACE_SOLID, "#262626"); assert.equal(d.ACCENT, "#FBD3C4"); assert.equal(d.ON_ACCENT, "#1B1B1B");
  // ⭐ D149 (owner 11-03) changed this on purpose: Dusk takes theme-dusk-v2.html's values; Light's coral is the sketch's
  // #C2593A moved the smallest step that holds AA under its white label (test/d149DuskDefault.test.js holds the moves).
  assert.equal(l.ACCENT, "#BE5739", "the sketch's coral, held at AA"); assert.equal(l.ON_ACCENT, "#FFFFFF", "… with a white label");
  // Answer 4: the mark stays draft's own — the orange slash in both, the word as Paper / Charcoal draw it.
  for (const t of [d, l]) assert.equal(t.LOGO_SLASH, "#FD4600");
  assert.equal(l.LOGO_WORD, THEMES["paper-light"].tokens.LOGO_WORD); assert.equal(d.LOGO_WORD, THEMES["charcoal-dark"].tokens.LOGO_WORD);
  assert.equal(d.INFO, "#9A9A9A", "answer 4: ordinary bars grey");
});

