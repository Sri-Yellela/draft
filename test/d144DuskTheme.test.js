test("d144ExistingThemesUnchanged: the six themes before Dusk are value for value what they were; the shape set is Dusk's only", () => {
  // D149 (owner 11-04, "go bold") ADDED the letter tile's keys to every theme; the pin covers every value that existed
  // before, so an addition is allowed and a change to an existing value is not.
  const D149_TILES = new Set(["TILE_BLUE", "TILE_GREEN", "TILE_PURPLE", "TILE_ORANGE", "TILE_TEAL", "TILE_SLATE", "TILE_ROSE", "ON_TILE",
    "CHART_NEUTRAL"]);   // ⭐ A228 (46r): + the skill map's chart neutral — another addition, no existing value changed
  const h = (t) => crypto.createHash("sha256").update(JSON.stringify({ tokens: Object.fromEntries(Object.entries(t.tokens).filter(([k]) => !D149_TILES.has(k))),
    substrate: t.substrate, label: t.label, scheme: t.scheme, contrast: t.contrast })).digest("hex");
  // The four D133 measured (test/d133StudioTheme.test.js), unchanged by D144.
  assert.equal(h(THEMES["paper-light"]), "b0460711d9592670ab80ff36e1a440cf42d914d4d23c0c08d388b2401fbf5911");
  assert.equal(h(THEMES["charcoal-dark"]), "245e41bae8565047444098f2cb17a41b3821a94704f7e5bf421dc8b3b01d17f8");
  assert.equal(THEME_LIST.length, 10);   // D181 (45l, on purpose): + Plain Light / Plain Dark
  assert.deepEqual(Object.keys(SHAPE_SETS).sort(), ["dusk-dark", "dusk-light"], "corners + type are OFF for every other theme");
  for (const id of Object.keys(SHAPE_SETS)) assert.deepEqual(Object.keys(SHAPE_SETS[id]).sort(), [...SHAPE_KEYS].sort());
  // Off = today's value, through the fallback in var().
  assert.equal(shape("RADIUS_CARD"), `var(--shape-radius-card, ${SHAPE_DEFAULTS.RADIUS_CARD})`);
  const el = (() => { const props = {}; return { props, dataset: {}, style: { setProperty: (k, v) => { props[k] = v; }, removeProperty: (k) => { delete props[k]; } } }; })();
  installShapeVars("paper-light", el);
  assert.deepEqual(el.props, {}); assert.equal(el.dataset.shape, undefined);
  installShapeVars("dusk-dark", el);
  assert.equal(el.props["--shape-radius-card"], "28px"); assert.equal(el.dataset.shape, "on");
  // ⭐ D149 (owner 11-03) changed this on purpose: Dusk is the DEFAULT, always offered — its admin switch no longer gates it.
  const ui = read("client/src/components/AppearanceSettings.jsx");
  assert.match(ui, /const duskOn = true;/);
  assert.match(ui, /\.filter\(\(c\) => duskOn \|\| !DUSK_IDS\.includes\(c\.id\)\)/);
  assert.match(read("server.js"), /const DUSK_FOR_USERS_KEY = "dusk_for_users";/);
});
