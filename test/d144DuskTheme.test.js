test("d144ContrastAA: the button, the figures and the body pass AA in both — and every declared pair at the theme's target", () => {
  for (const id of DUSK_IDS) {
    const t = THEMES[id].tokens;
    assert.ok(ratio(t.ON_ACCENT, t.ACCENT) >= 4.5, `${id}: the button's label ${ratio(t.ON_ACCENT, t.ACCENT).toFixed(2)}`);
    assert.ok(ratio(t.ACCENT_INK, t.SURFACE_SOLID) >= 4.5, `${id}: the figures on a card`);
    assert.ok(ratio(t.ACCENT_INK, t.CANVAS) >= 4.5, `${id}: the figures on the ground`);
    assert.ok(ratio(t.INK_MUTED, t.SURFACE_SOLID) >= 4.5, `${id}: the body grey on a card`);
    assert.ok(ratio(t.INK, t.CANVAS) >= 7, `${id}: headlines`);
  }
  // The whole contract (test/d91ThemeModule.test.js runs it for every registry theme) — re-run here for Dusk's two.
  const fails = [];
  let n = 0;
  for (const id of DUSK_IDS) for (const [fg, bg, size] of CONTRAST_PAIRS) {
    const t = THEMES[id].tokens;
    if (!hex(t[fg]) || !hex(t[bg])) continue;   // translucent pairs are composited by test/d91ThemeModule.test.js
    n++;
    const need = pairTarget(THEMES[id].contrast, fg, bg, size);
    if (ratio(t[fg], t[bg]) < need) fails.push(`${id}: ${fg} on ${bg} ${ratio(t[fg], t[bg]).toFixed(2)} < ${need}`);
  }
  assert.ok(n > 100, "the pairs were read");
  assert.deepEqual(fails, []);
});

