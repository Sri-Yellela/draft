test("d133ContrastAA: every declared pair passes AA in both Studio themes", () => {
  const parse = (v) => { let m = /^#([0-9a-f]{6})$/i.exec(v); if (m) return { rgb: [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16)), a: 1 };
    m = /^rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([0-9.]+))?\)$/.exec(v); return { rgb: [+m[1], +m[2], +m[3]], a: m[4] === undefined ? 1 : +m[4] }; };
  const ch = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
  const lum = ([r, g, b]) => 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b);
  const failures = [];
  for (const id of STUDIO_IDS) {
    const T = THEMES[id].tokens;
    const opaque = (v, under = T.CANVAS_SHADE) => { const { rgb, a } = parse(v in T ? T[v] : v); if (a === 1) return rgb; const b = opaque(under); return rgb.map((c, i) => c * a + b[i] * (1 - a)); };
    for (const [fg, bg, size] of CONTRAST_PAIRS) {
      const [hi, lo] = [lum(opaque(fg)), lum(opaque(bg))].sort((x, y) => y - x);
      const r = (hi + 0.05) / (lo + 0.05), need = pairTarget("aa", fg, bg, size);
      if (r < need) failures.push(`${id}: ${fg} on ${bg} ${r.toFixed(2)} < ${need}`);
    }
  }
  assert.ok(CONTRAST_PAIRS.length >= 100);
  assert.deepEqual(failures, []);
});
