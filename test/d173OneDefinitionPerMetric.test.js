// D173 (4) · one definition per number — shared/metricDefinitions.js is held to the code.
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { METRICS } from "../shared/metricDefinitions.js";

const read = (p) => fs.readFileSync(p, "utf8");
const tracked = () => execFileSync("git", ["ls-files", "*.js", "*.mjs", "*.jsx"], { encoding: "utf8" }).split("\n").filter(Boolean)
  .filter(f => !f.startsWith("test/") && !f.includes("node_modules/") && !f.startsWith("client/dist/") && !f.startsWith("extension/submission/"));

test("each number's ONE function exists where the registry says", () => {
  for (const m of METRICS) {
    const src = read(m.module);
    assert.match(src, new RegExp(`export (async )?function ${m.fn}\\b`), `${m.id}: ${m.module} exports ${m.fn}`);
    assert.ok(m.plain && m.plain.length > 20, `${m.id} has a plain definition`);
  }
});

test("no other file defines a function by the same name (a second implementation)", () => {
  const files = tracked();
  for (const m of METRICS) {
    const def = new RegExp(`(^|\\n)\\s*(export\\s+)?(async\\s+)?function\\s+${m.fn}\\s*\\(`);
    const others = files.filter(f => path.normalize(f) !== path.normalize(m.module) && def.test(read(f)))
      // the scorer's one sanctioned re-export, with the same inputs (services/localAtsScorer.js)
      .filter(f => !(m.fn === "scoreAtsLocally" && f === "services/localAtsScorer.js"))
      // a GENERATED byte copy of the same source for the extension (it cannot import) — t9AtsReportComponent holds it equal
      .filter(f => !(f.startsWith("extension/") && /^\/\* GENERATED by scripts\//.test(read(f))));
    assert.deepEqual(others, [], `${m.fn} is defined again in ${others.join(", ")}`);
  }
});
